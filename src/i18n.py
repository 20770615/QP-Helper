_PLACEHOLDER_SKILLS = [
    ("skill.gen_report", "gen_report"),
    ("Fund rebalance suggestion", "rebalance"),
    ("Locate documents", "locate"),
    ("Summarize emails", "summarize"),
]

_TAG_DISPLAY_NAMES = {}


def t(key: str, **kwargs) -> str:
    """Return the localized string for `key` in the active language.

    Falls back to English, then to the key itself, so a missing key never
    crashes the UI.
    """
    lang = get_language() or "zh"
    table = I18N.get(lang) or I18N.get("en") or {}
    s = table.get(key)
    if s is None:
        s = (I18N.get("en") or {}).get(key, key)
    if kwargs:
        try:
            return s.format(**kwargs)
        except Exception:
            return s
    return s


def placeholder_skills():
    """Return (localized_label, skill_id) placeholder skills for the Home + menu."""
    out = []
    for label_or_key, sid in _PLACEHOLDER_SKILLS:
        label = t(label_or_key) if "." in label_or_key else label_or_key
        # if key missing, t returns key; for plain english labels keep as-is
        if label == label_or_key and "." not in label_or_key:
            label = label_or_key
        elif label == label_or_key and label_or_key in (I18N.get("en") or {}):
            label = (I18N.get("en") or {})[label_or_key]
        out.append((label if not label.startswith("skill.") else (I18N.get("en") or {}).get(label_or_key, label_or_key), sid))
    # Prefer proper t() for skill keys
    fixed = []
    for label_or_key, sid in _PLACEHOLDER_SKILLS:
        if label_or_key.startswith("skill.") or "." in label_or_key and label_or_key in (I18N.get("en") or {}):
            fixed.append((t(label_or_key), sid))
        else:
            # plain bilingual handled via zh table if present as value-only — keep EN literal and ZH via optional map
            zh_map = {
                "Fund rebalance suggestion": "调仓建议",
                "Locate documents": "定位文档",
                "Summarize emails": "总结邮件",
            }
            lang = get_language() or "zh"
            if lang == "zh":
                fixed.append((zh_map.get(label_or_key, label_or_key), sid))
            else:
                fixed.append((label_or_key, sid))
    return fixed


def tag_display_name(tag: str) -> str:
    return _TAG_DISPLAY_NAMES.get(tag, tag)
